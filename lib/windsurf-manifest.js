import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Filename of the provenance manifest the windsurf adapter drops into
 * `.windsurf/rules/`.
 *
 * The leading dot matters twice: Windsurf itself only reads `*.md`, and both
 * rule walkers in this package skip dot-entries — so the manifest can never be
 * mistaken for a rule.
 */
export const WINDSURF_MANIFEST = '.spovishun-manifest.json';

/** Bumped only on a breaking change to the on-disk shape. */
export const WINDSURF_MANIFEST_VERSION = 1;

/**
 * Why this file exists at all.
 *
 * `.windsurf/rules/` is a FLAT directory of `.md` files, so the windsurf
 * adapter has to flatten three different id namespaces into one filename space:
 *
 *   skill  `universal-skill`              → universal-skill.md
 *   rule   `common/git-workflow`          → common--git-workflow.md
 *   support `universal-skill/references/x.md` → universal-skill--references--x.md
 *   any of the above, over CHAR_LIMIT     → <base>-part-1.md, -part-2.md, …
 *
 * That mapping is lossy: `--` stands for both a path separator and the
 * body/support boundary, and nothing in a filename records the artifact KIND.
 * The reader used to guess it back and got it wrong — every rule and every
 * supporting file was announced as a `skill:`, keys the lockfile never contains,
 * which made ownership for this target impossible by construction.
 *
 * So the writer records what it knows instead of the reader guessing. The
 * manifest is generated data, never hand-edited; a consumer who deletes it
 * falls back to filename parsing (see lib/installed-files-loader.js).
 *
 * Shape:
 *   {
 *     version: 1,
 *     files: {
 *       "<filename>.md": { kind, id, role: 'body'|'support', part?: <1-based> }
 *     }
 *   }
 *
 * `kind` / `id` are the LOCKFILE identity (`rule` + `common/git-workflow`), not
 * the filename-derived one, which is the whole point.
 */

/**
 * @param {string} rulesDir — absolute path to `.windsurf/rules/`
 * @param {Object<string, {kind: string, id: string, role: string, part?: number}>} files
 */
export function writeWindsurfManifest(rulesDir, files) {
  const data = {
    version: WINDSURF_MANIFEST_VERSION,
    _comment: 'Auto-generated by `spovishun-skills install --target=windsurf`. Do not edit manually.',
    files,
  };
  writeFileSync(join(rulesDir, WINDSURF_MANIFEST), JSON.stringify(data, null, 2) + '\n', 'utf8');
}

/**
 * Reads the manifest, or returns null when it is absent or unusable.
 *
 * A malformed or future-versioned manifest reads as absent rather than as an
 * error: the caller's fallback (filename parsing) is always a valid answer, and
 * `install` must never be bricked by a file it generated itself.
 *
 * @param {string} rulesDir — absolute path to `.windsurf/rules/`
 * @returns {Object<string, {kind: string, id: string, role: string, part?: number}>|null}
 */
export function readWindsurfManifest(rulesDir) {
  let raw;
  try {
    raw = readFileSync(join(rulesDir, WINDSURF_MANIFEST), 'utf8');
  } catch {
    return null;
  }

  let data;
  try {
    data = JSON.parse(raw);
  } catch {
    return null;
  }

  if (data?.version !== WINDSURF_MANIFEST_VERSION) return null;
  if (!data.files || typeof data.files !== 'object') return null;
  return data.files;
}
